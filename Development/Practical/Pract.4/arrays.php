<h2>Задание 4</h2>
<p>Преобразовать массив вещественных чисел по правилу: положительные элементы заменить их квадратами, отрицательные - абсолютными величинами. Для этого создайте еще один массив.</p>
<p>arr = [1.5, -2.3, 4.0, -5.1, 3.7]</p>
<?php
$arr = [1.5, -2.3, 4.0, -5.1, 3.7];
$new_arr = [];

foreach ($arr as $num) {
    if ($num > 0) {
        $new_arr[] = $num * $num; // Квадрат
    } else {
        $new_arr[] = abs($num);   // Модуль (убираем минус)
    }
}
echo "Исходный: " . implode(", ", $arr) . "<br>";
echo "Новый: " . implode(", ", $new_arr) . "<br>";
?>
<h2>Задание 5</h2>
<p>Дан массив, состоящий из целых чисел. Нумерация элементов начинается с 0. Напишите программу, которая выведет элементы массива, номера которых четны (0, 2, 4...).</p>
<?php
$arr = [2,10, 20, 30, 34, 50, 60];
$result = [];

for ($i = 0; $i < count($arr); $i++) {
    if ($i % 2 == 0) { // Если индекс четный
        $result[]= $arr[$i];
    }
}
echo "Четные индексы: " . implode(", ", $result) . "<br>";
