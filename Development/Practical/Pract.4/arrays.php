<h2>Задание 1</h2>
<p>Дан неупорядоченный массив целых чисел.

Найти максимальный и минимальный элемент массива.

Вывести их номера(индексы) и значения.</p>
<p>arr = [5, 12, 8, -3, 45, 0, 22]</p><?php
$arr = [5, 12, 8, -3, 45, 0, 22];
$max = $arr[0];
$min = $arr[0];
$max_i = 0;
$min_i = 0;

for ($i = 1; $i < count($arr); $i++) {
    if ($arr[$i] > $max) {
        $max = $arr[$i];
        $max_i = $i;
    }
    if ($arr[$i] < $min) {
        $min = $arr[$i];
        $min_i = $i;
    }
}
echo "Массив: " . implode(", ", $arr) . "<br>";
echo "Максимум: $max (индекс $max_i)<br>";
echo "Минимум: $min (индекс $min_i)<br>";
?>
